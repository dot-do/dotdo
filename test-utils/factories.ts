/**
 * Test Data Factories for @dotdo
 *
 * This module provides factory functions for creating test data.
 * These factories create valid data structures for Things, Events,
 * Relationships, and other domain objects.
 *
 * @module test-utils/factories
 */

import { generateTestId } from './helpers'
import type { Thing, Event, Relationship } from './assertions'

// Re-export types for convenience
export type { Thing, Event, Relationship }

// ============================================================================
// Thing Factories
// ============================================================================

/**
 * Input data for creating a Thing.
 * Mirrors the structure expected by things.create()
 */
export interface ThingInput {
  $type: string
  [key: string]: unknown
}

/**
 * Create a Thing input object for testing.
 *
 * Generates valid input data for creating a Thing via the things store.
 * Does not include system fields ($id, $createdAt, $updatedAt) as those
 * are generated by the store.
 *
 * @param overrides - Fields to override or add
 * @returns A valid ThingInput object
 *
 * @example
 * ```typescript
 * // Create a Customer input
 * const customerInput = createThingInput({ $type: 'Customer', name: 'Alice' })
 * const customer = await things.create(customerInput)
 *
 * // Create with defaults
 * const defaultInput = createThingInput()
 * // { $type: 'TestThing' }
 * ```
 */
export function createThingInput(overrides: Partial<ThingInput> = {}): ThingInput {
  return {
    $type: 'TestThing',
    ...overrides
  }
}

/**
 * Create a complete Thing object for testing.
 *
 * Generates a complete Thing including system fields.
 * Useful for mocking or testing code that expects complete Things.
 *
 * @param overrides - Fields to override
 * @returns A complete Thing object
 *
 * @example
 * ```typescript
 * const customer = createThing({ $type: 'Customer', name: 'Alice' })
 * expect(customer.$id).toBeDefined()
 * expect(customer.$createdAt).toBeLessThanOrEqual(Date.now())
 * ```
 */
export function createThing(overrides: Partial<Thing> = {}): Thing {
  const now = Date.now()
  return {
    $id: generateTestId('thing'),
    $type: 'TestThing',
    $createdAt: now,
    $updatedAt: now,
    ...overrides
  }
}

/**
 * Create multiple Thing input objects for testing.
 *
 * @param count - Number of Things to create
 * @param baseOverrides - Base overrides for all Things
 * @param customizer - Optional function to customize each Thing
 * @returns Array of ThingInput objects
 *
 * @example
 * ```typescript
 * const inputs = createThingInputs(3, { $type: 'Customer' }, (i) => ({
 *   name: `Customer ${i + 1}`
 * }))
 * // [
 * //   { $type: 'Customer', name: 'Customer 1' },
 * //   { $type: 'Customer', name: 'Customer 2' },
 * //   { $type: 'Customer', name: 'Customer 3' }
 * // ]
 * ```
 */
export function createThingInputs(
  count: number,
  baseOverrides: Partial<ThingInput> = {},
  customizer?: (index: number) => Partial<ThingInput>
): ThingInput[] {
  return Array.from({ length: count }, (_, i) =>
    createThingInput({
      ...baseOverrides,
      ...(customizer ? customizer(i) : {})
    })
  )
}

