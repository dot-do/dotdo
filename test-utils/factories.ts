/**
 * Create a batch of related test data.
 *
 * Generates a set of Things and Relationships that are interconnected.
 * Useful for testing complex scenarios involving multiple entities.
 *
 * @param options - Configuration for the batch
 * @returns Object containing inputs for Things and Relationships
 *
 * @example
 * ```typescript
 * const batch = createTestBatch({
 *   customers: 2,
 *   ordersPerCustomer: 3
 * })
 *
 * // Create customers
 * const customers = await things.bulkCreate(batch.customers)
 *
 * // Create orders
 * const orders = await things.bulkCreate(batch.orders)
 *
 * // Create relationships
 * for (const rel of batch.relationships) {
 *   await relationships.add(rel)
 * }
 * ```
 */
export function createTestBatch(options: {
  customers?: number
  ordersPerCustomer?: number
} = {}): {
  customers: ThingInput[]
  orders: ThingInput[]
  relationships: RelationshipInput[]
} {
  const { customers: customerCount = 2, ordersPerCustomer = 2 } = options

  const customers: ThingInput[] = []
  const orders: ThingInput[] = []
  const relationships: RelationshipInput[] = []

  for (let c = 0; c < customerCount; c++) {
    const customerId = `customer-${c + 1}`
    customers.push(createCustomerInput({ name: `Customer ${c + 1}` }))

    for (let o = 0; o < ordersPerCustomer; o++) {
      const orderId = `order-${c + 1}-${o + 1}`
      orders.push(createOrderInput({ total: (c + 1) * 100 + (o + 1) * 10 }))
      relationships.push(createRelationshipInput({
        subject: customerId,
        predicate: 'placed',
        object: orderId
      }))
    }
  }

  return { customers, orders, relationships }
}
